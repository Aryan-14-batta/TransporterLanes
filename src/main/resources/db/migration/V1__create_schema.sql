-- Portable SQL: runs unchanged on PostgreSQL (application) and H2 in PostgreSQL mode (tests).

-- Lane and transporter ids are supplied by the client, so they are not generated.
CREATE TABLE lane (
    id          BIGINT       NOT NULL,
    origin      VARCHAR(100) NOT NULL,
    destination VARCHAR(100) NOT NULL,
    CONSTRAINT pk_lane PRIMARY KEY (id),
    CONSTRAINT ck_lane_id_positive CHECK (id > 0)
);

CREATE TABLE transporter (
    id   BIGINT       NOT NULL,
    name VARCHAR(200) NOT NULL,
    CONSTRAINT pk_transporter PRIMARY KEY (id),
    CONSTRAINT ck_transporter_id_positive CHECK (id > 0)
);

-- One row per (lane, transporter) price. Quotes are whole rupees, at most 1 lakh crore (10^12).
CREATE TABLE lane_quote (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    lane_id        BIGINT NOT NULL,
    transporter_id BIGINT NOT NULL,
    quote          BIGINT NOT NULL,
    CONSTRAINT pk_lane_quote PRIMARY KEY (id),
    CONSTRAINT fk_lane_quote_lane FOREIGN KEY (lane_id) REFERENCES lane (id),
    CONSTRAINT fk_lane_quote_transporter FOREIGN KEY (transporter_id) REFERENCES transporter (id),
    CONSTRAINT uk_lane_quote_lane_transporter UNIQUE (lane_id, transporter_id),
    CONSTRAINT ck_lane_quote_quote_range CHECK (quote > 0 AND quote <= 1000000000000)
);

-- The unique constraint already indexes lane_id first; this covers lookups and FK checks by transporter.
CREATE INDEX idx_lane_quote_transporter ON lane_quote (transporter_id);
